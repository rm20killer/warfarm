export function getBoss(idOrName: string): BossEntity | undefined {
  const norm = idOrName.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '');
  return ALL_BOSSES.find((b) => b.id === norm || b.name.toLowerCase() === idOrName.toLowerCase());
}

